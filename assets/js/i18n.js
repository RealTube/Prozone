  var root = document.documentElement;
  var lang = root.getAttribute('data-lang') || 'en';
  var dict = DICT[lang] || null;

  window.PZ_LANG = lang;
  window.PZ_T = function (key, fallback) { return (dict && dict[key] != null) ? dict[key] : fallback; };

  if (dict) {
    Array.prototype.forEach.call(document.querySelectorAll('[data-i18n]'), function (el) {
      var v = dict[el.getAttribute('data-i18n')];
      if (v != null) el.innerHTML = v;
    });
    Array.prototype.forEach.call(document.querySelectorAll('[data-i18n-attr]'), function (el) {
      el.getAttribute('data-i18n-attr').split(',').forEach(function (pair) {
        var p = pair.split(':'), v = dict[(p[1] || '').trim()];
        if (v != null) el.setAttribute(p[0].trim(), v.replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' '));
      });
    });
  }

  // Language switchers: mark the current one, remember the choice
  Array.prototype.forEach.call(document.querySelectorAll('[data-set-lang]'), function (a) {
    var code = a.getAttribute('data-set-lang');
    if (code === lang) a.setAttribute('aria-current', 'true');
    a.addEventListener('click', function () {
      try { localStorage.setItem('pz-lang', code); } catch (e) {}
    });
  });

  root.classList.remove('i18n-wait');
